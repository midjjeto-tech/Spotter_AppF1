# Поиск: длинные ключи раньше; границы — не-латинские символы.
_LEX_LOWER = {k.lower(): v for k, v in _LEXICON.items()}
_LEX_KEYS = sorted(_LEXICON.keys(), key=len, reverse=True)
_LEX_RE = re.compile(
    r'(?<![A-Za-z])(' + '|'.join(re.escape(k) for k in _LEX_KEYS) + r')(?![A-Za-z])',
    re.IGNORECASE,
)

# ──────────────────────────────────────────────────────────────────────────
# 3. ИСПРАВЛЕНИЕ УДАРЕНИЙ (rule 3)  — пословное переписывание (ВЕРИФИЦИРОВАНО)
#    '+' не работает (см. шапку). Двигаем ударение, переписывая слово так, что
#    espeak ставит его верно. Каждую пару проверять через phonemize!
#    Ключ — реальное слово (lower), значение — форма, которую espeak читает верно.
# ──────────────────────────────────────────────────────────────────────────
_STRESS_FIXES: dict[str, str] = {
    # Проверено через piper.phonemize_espeak (ru):
    # Серхйо → sʲˈerxjʌ; Ландъо → ɭˈɑndʌ.
    # Фамилии Перес, Норрис и Ферстаппен espeak уже произносит с верным ударением.
    "серхио": "серхйо",
    "ландо": "ландъо",
}
_STRESS_RE = (
    re.compile(r'(?<![А-Яа-яЁё])(' + '|'.join(re.escape(k) for k in _STRESS_FIXES) + r')(?![А-Яа-яЁё])', re.I)
    if _STRESS_FIXES else None
)


def _preserve_case(source: str, replacement: str) -> str:
    """Перенести регистр исходного имени на фонетическое написание."""
    if source.isupper():
        return replacement.upper()
    if source[:1].isupper():
        return replacement[:1].upper() + replacement[1:]
    return replacement

# ──────────────────────────────────────────────────────────────────────────
# 5. ГОД → ПОРЯДКОВОЕ (rule 5).  Числа в остальном espeak читает сам.
# ──────────────────────────────────────────────────────────────────────────
_UNITS = ["", "первый", "второй", "третий", "четвёртый", "пятый", "шестой",
          "седьмой", "восьмой", "девятый"]
_TEENS = {10: "десятый", 11: "одиннадцатый", 12: "двенадцатый", 13: "тринадцатый",
          14: "четырнадцатый", 15: "пятнадцатый", 16: "шестнадцатый",
          17: "семнадцатый", 18: "восемнадцатый", 19: "девятнадцатый"}
_TENS = {20: "двадцат", 30: "тридцат", 40: "сороков", 50: "пятидесят",
         60: "шестидесят", 70: "семидесят", 80: "восьмидесят", 90: "девяност"}
_TENS_CARD = {20: "двадцать", 30: "тридцать", 40: "сорок", 50: "пятьдесят",
              60: "шестьдесят", 70: "семьдесят", 80: "восемьдесят", 90: "девяносто"}


def _two_digit_ordinal(n: int) -> str:
    """1..99 → порядковое (мужской род): 26 → 'двадцать шестой', 30 → 'тридцатый'."""
    if n <= 0:
        return ""
    if n < 10:
        return _UNITS[n]
    if 10 <= n <= 19:
        return _TEENS[n]
    tens, ones = (n // 10) * 10, n % 10
    if ones == 0:
        return _TENS[tens] + "ый"
    return _TENS_CARD[tens] + " " + _UNITS[ones]


def _year_to_ordinal(year: int) -> str | None:
    """1000..2099 → 'две тысячи двадцать шестой' и т.п. Вне диапазона — None."""
    if not (1000 <= year <= 2099):
        return None
    thousands = year // 1000
    rest = year % 1000
    hundreds = rest // 100
    last2 = rest % 100
    parts: list[str] = []
    parts.append("одна тысяча" if thousands == 1 else "две тысячи")
    h_words = {1: "сто", 2: "двести", 3: "триста", 4: "четыреста", 5: "пятьсот",
               6: "шестьсот", 7: "семьсот", 8: "восемьсот", 9: "девятьсот"}
    if last2 == 0 and hundreds != 0:
        h_ord = {1: "сотый", 2: "двухсотый", 3: "трёхсотый", 4: "четырёхсотый",
                 5: "пятисотый", 6: "шестисотый", 7: "семисотый", 8: "восьмисотый",
                 9: "девятисотый"}
        parts.append(h_ord[hundreds])
        return " ".join(parts)
    if hundreds:
        parts.append(h_words[hundreds])
    if last2:
        parts.append(_two_digit_ordinal(last2))
    elif not hundreds:
        # ровно тысяча/две тысячи: "тысячный"/"двухтысячный"
        return "тысячный" if thousands == 1 else "двухтысячный"
    return " ".join(parts)


_YEAR_RE = re.compile(r'\b(\d{4})\s+(год\w*)\b', re.I)


def _year_sub(m: re.Match) -> str:
    words = _year_to_ordinal(int(m.group(1)))
    return f"{words} {m.group(2)}" if words else m.group(0)


# ──────────────────────────────────────────────────────────────────────────
# Фолбэк-транслитерация: любой ОСТАВШИЙСЯ латинский токен → кириллица,
# чтобы ни одно английское слово не дошло до espeak «как есть».
# ──────────────────────────────────────────────────────────────────────────
_LETTER_NAMES = {
    "a": "а", "b": "бэ", "c": "цэ", "d": "дэ", "e": "е", "f": "эф", "g": "гэ",
    "h": "аш", "i": "и", "j": "джей", "k": "ка", "l": "эль", "m": "эм", "n": "эн",
    "o": "о", "p": "пэ", "q": "ку", "r": "эр", "s": "эс", "t": "тэ", "u": "у",
    "v": "вэ", "w": "дабл-ю", "x": "икс", "y": "игрек", "z": "зэт",
}
_DIGRAPHS = [
    ("sch", "ш"), ("sh", "ш"), ("ch", "ч"), ("ck", "к"), ("th", "т"),
    ("ph", "ф"), ("oo", "у"), ("ee", "и"), ("ou", "ау"), ("ay", "эй"),
    ("ey", "эй"), ("ya", "я"), ("yu", "ю"), ("yo", "ё"), ("ja", "я"),
]
_MONO = {
    "a": "а", "b": "б", "c": "к", "d": "д", "e": "е", "f": "ф", "g": "г",
    "h": "х", "i": "и", "j": "дж", "k": "к", "l": "л", "m": "м", "n": "н",
    "o": "о", "p": "п", "q": "к", "r": "р", "s": "с", "t": "т", "u": "у",
    "v": "в", "w": "в", "x": "кс", "y": "й", "z": "з",
}
_VOWELS = set("aeiouy")


def _spell_letters(token: str) -> str:
    return "-".join(_LETTER_NAMES.get(c, c) for c in token.lower())


def _translit(token: str) -> str:
    s = token.lower()
    for a, b in _DIGRAPHS:
        s = s.replace(a, b)
    out = []
    for c in s:
        out.append(_MONO.get(c, c))
    return "".join(out)


def _convert_latin(token: str) -> str:
    low = token.lower()
    if low in _LEX_LOWER:
        return _LEX_LOWER[low]
    # короткая аббревиатура или набор согласных → читаем по буквам
    if (token.isupper() and len(token) <= 5) or (len(token) <= 4 and not any(c in _VOWELS for c in low)):
        return _spell_letters(token)
    return _translit(token)


_LATIN_RUN_RE = re.compile(r'[A-Za-z]+')


def _latin_fallback_sub(m: re.Match) -> str:
    return _convert_latin(m.group(0))


# ──────────────────────────────────────────────────────────────────────────
def normalize(text: str) -> str:
    """Готовит русский текст для Piper. Никогда не бросает исключение."""
    if not text:
        return text
    try:
        s = replace_known_driver_names(str(text))
        # 1. дефектные фразы
        for pattern, repl in _PHRASE_FIXES:
            s = pattern.sub(repl, s)
        # 5. год → порядковое (до общей обработки латиницы/чисел)
        s = _YEAR_RE.sub(_year_sub, s)
        # 2. словарь латиница → кириллица
        s = _LEX_RE.sub(lambda m: _LEX_LOWER[m.group(0).lower()], s)
        # 2b. фолбэк: оставшаяся латиница → транслит/по буквам
        s = _LATIN_RUN_RE.sub(_latin_fallback_sub, s)
        # 3. точечные исправления ударений
        if _STRESS_RE is not None:
            s = _STRESS_RE.sub(
                lambda m: _preserve_case(m.group(0), _STRESS_FIXES[m.group(0).lower()]),
                s,
            )
        # финальная чистка пробелов
        s = re.sub(r'\s+', ' ', s).strip()
        return s
    except Exception:
        return text
