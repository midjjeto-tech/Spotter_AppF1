"""
new_tts/ru_textnorm.py
======================
Лингвистическая предобработка текста для Piper (русские голоса).

ЧТО РАБОТАЕТ и ЧТО НЕТ (проверено эмпирически на espeak-ng внутри Piper 1.4.2):

  ✗ Знак '+' перед гласной для ударения — НЕ работает: espeak читает его
    буквально как слово «плюс» (з+амок → «зэ плюс амок»). НЕ использовать.
  ✗ Комбинирующий акцент U+0301 (за́мок) — espeak игнорирует.
  ✗ Маркеры ˈ / ' — игнорируются или читаются как «stress».
  ✓ Замена латиницы на кириллицу — espeak читает кириллицу русскими фонемами.
    Это главный и надёжный приём (Google → «гугл», а не английское ˈɡuːɡəl).
  ✓ Управление паузами — дроблением на короткие сегменты (делает piper_tts).
  ✓ Числа — espeak сам читает по-русски (320 → «триста двадцать»).
  ~ Ударение в проблемных словах — только переписыванием слова (трюк с «ё»
    или фонетической кириллицей), пословно, см. _STRESS_FIXES. Общего способа нет.

normalize() НИКОГДА не бросает исключение — при ошибке возвращает вход как есть.
"""
from __future__ import annotations

import re

