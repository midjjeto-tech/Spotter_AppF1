# ──────────────────────────────────────────────────────────────────────────
# 1. ИСПРАВЛЕНИЕ ДЕФЕКТНЫХ ФРАЗ (rule 1)
#    Конкретные кривые конструкции → грамматичные, легкопроизносимые.
# ──────────────────────────────────────────────────────────────────────────
_PHRASE_FIXES: list[tuple[re.Pattern, str]] = [
    (re.compile(r'\bработа\s+спот\w*\s+об\s+готова\b', re.I), 'Работа Споттера полностью завершена'),
    (re.compile(r'\bприложени\w*\s+об\s+готова\b', re.I), 'Приложение готово к работе'),
    (re.compile(r'\bоб\s+готов', re.I), 'готов'),
    # позиции: P1..P20 -> "позиция N" (espeak затем прочитает N по-русски)
    (re.compile(r'\bP(\d{1,2})\b', re.I), r'позиция \1'),
]

# ──────────────────────────────────────────────────────────────────────────
# 2. ЛАТИНИЦА → КИРИЛЛИЦА (rule 2)  — главный приём
