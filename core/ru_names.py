# Полное имя → фамилия (последний токен), чтобы decline() принимал и «Макс
# Ферстаппен» (как в событиях), и «Ферстаппен» (как в тестах/радио).
# Сезонно-нейтрально: "фамилия = последнее слово" не зависит от того, какой
# сезон активен сейчас, поэтому объединяем 2025+2026, а не выбираем по году.
_FULL_TO_SURNAME: dict[str, str] = {
    full: full.split()[-1]
    for full, _team in {**F1_2025_BY_NUMBER, **F1_2026_BY_NUMBER}.values()
}

_CASES = ("nom", "gen", "dat", "acc", "ins")

# Краткие подписи падежей для шпаргалки LLM (glossary).
_CASE_LABELS: dict[str, str] = {
    "nom": "им", "gen": "род", "dat": "дат", "acc": "вин", "ins": "тв",
}

# Метки, которые не нужно класть в шпаргалку склонений (не реальные имена).
_SKIP_IN_GLOSSARY = {"", "player", "—", "оппонент", "соперник", "гонщик", "пилот"}


def surname_of(name: str) -> str:
    """Фамилия (последний токен полного имени). Неизвестное имя — как есть."""
    if not name:
        return name
    return _FULL_TO_SURNAME.get(name, name.split()[-1])


def first_name_of(name: str | None) -> str | None:
    """Имя игрока для обращения по радио («Макс, …» — см. commentator/personas.py,
    персона "calm"). None — если имя неизвестно или это служебная метка
    (кастомный пилот "Моя команда", данные UDP ещё не пришли) — в этом случае
    вызывающий код не должен подставлять никакое имя в контекст для LLM."""
    if not name or name.strip().lower() in _SKIP_IN_GLOSSARY:
        return None
    return name.split()[0]


def decline(name: str, case: str = "nom") -> str:
    """Фамилия пилота в нужном падеже.

    name — полное имя («Макс Ферстаппен») или фамилия («Ферстаппен») или
    родовая метка («соперник»). Неизвестные/кастомные имена → фамилия без
    склонения (лучше так, чем подставлять чужой падеж). case ∈ _CASES.
    """
    if not name:
        return name
    surname = surname_of(name)
    if case == "nom" or case not in _CASES:
        return surname
    forms = _FORMS.get(surname)
    if forms:
        return forms.get(case, surname)
    return surname  # несклоняемая или неизвестная фамилия


def glossary(names: Iterable[str]) -> str:
    """Шпаргалка склонений для имён в контексте — для подмешивания в промпт LLM.

    Возвращает по строке на пилота: «Албон: им. Албон, род. Албона, дат. Албону,
    вин. Албона, тв. Албоном». Несклоняемые отмечаются явно. Дубли и служебные
    метки (player/соперник/«#N») отбрасываются. Пустой ввод → пустая строка.
    """
    seen: set[str] = set()
    lines: list[str] = []
    for name in names:
        if not name or name.startswith("#"):
            continue
        surname = surname_of(name)
        if surname in seen or surname in _SKIP_IN_GLOSSARY or not surname:
            continue
        seen.add(surname)
        forms = {c: decline(surname, c) for c in _CASES}
        if len(set(forms.values())) == 1:           # несклоняемая
            lines.append(f"{surname}: не склоняется (везде «{surname}»)")
        else:
            parts = ", ".join(f"{_CASE_LABELS[c]}. {forms[c]}" for c in _CASES)
            lines.append(f"{surname}: {parts}")
    return "\n".join(lines)
