"""
core/radio/corner_words.py
===========================
Как назвать поворот В РЕЧИ.

**Имя поворота из справочника трасс для озвучки не годится, и это измеримо.**
Из 325 поворотов на 24 трассах имя есть у 109 (33%), и ВСЕ 109 — латиницей:
`Tamburello 1`, `La Source`, `Tarzanbocht`, `Variante del Rettifilo`. Двенадцать
трасс из двадцати четырёх не имеют имён вовсе. Русский синтез читает латиницу
как набор букв — ровно тот класс брака, который уже чинили для фамилий пилотов
(см. `core/transliterate.py`).

**Поэтому в эфир едет НОМЕР, а не имя:** «в седьмом повороте». Номер есть у
100% поворотов, так говорят в реальной команде («lock-up into turn 3»), и
морфология закрывается таблицей, а не библиотекой. Имена остаются в дебрифе,
где их читают глазами, а не слушают.

Падеж один — ПРЕДЛОЖНЫЙ, и другого здесь быть не должно: банк фраз ставит токен
только после предлога «в». Родительный («на выходе из седьмого») потребовал бы
второй формы и второго повода ошибиться в согласовании; вместо этого фразы
построены так, чтобы обходиться одним падежом.
"""
from __future__ import annotations

#: Порядковые числительные в предложном падеже, мужской род (поворот — он).
#: До двадцати — таблицей: это ровно тот диапазон, где формы нерегулярны.
_ONES: dict[int, str] = {
    1: "первом", 2: "втором", 3: "третьем", 4: "четвёртом", 5: "пятом",
    6: "шестом", 7: "седьмом", 8: "восьмом", 9: "девятом", 10: "десятом",
    11: "одиннадцатом", 12: "двенадцатом", 13: "тринадцатом",
    14: "четырнадцатом", 15: "пятнадцатом", 16: "шестнадцатом",
    17: "семнадцатом", 18: "восемнадцатом", 19: "девятнадцатом",
    20: "двадцатом",
}

#: Дальше числительное составное, и склоняется только последнее слово:
#: «в двадцать первом», «в тридцатом». Самая длинная трасса календаря даёт 16
#: поворотов, так что это запас на моды и будущие трассы, а не рабочий диапазон.
_TENS: dict[int, str] = {20: "двадцать", 30: "тридцать"}
_TENS_ALONE: dict[int, str] = {20: "двадцатом", 30: "тридцатом"}

MAX_CORNER = 39


def ordinal_prepositional(corner_id: int | None) -> str | None:
    """«седьмом» для 7. None — если назвать поворот нечем.

    None, а не заглушка: фраза без номера должна не прозвучать вовсе, а не
    прозвучать с дырой. Вызывающий обязан это проверить."""
    # Строго целое, и НЕ через int(): int(2.5) дал бы «втором», то есть назвал
    # бы пилоту не тот поворот. Дробный или строковый id — это испорченные
    # данные справочника, и промолчать здесь честнее, чем округлить.
    # bool исключён отдельно: он подкласс int, и True превратился бы в «первом».
    if not isinstance(corner_id, int) or isinstance(corner_id, bool):
        return None
    number = corner_id
    if number < 1 or number > MAX_CORNER:
        return None
    if number in _ONES:
        return _ONES[number]
    tens, ones = divmod(number, 10)
    tens *= 10
    if ones == 0:
        return _TENS_ALONE.get(tens)
    prefix = _TENS.get(tens)
    if prefix is None:
        return None
    return f"{prefix} {_ONES[ones]}"
