"""
core/radio/euphony.py
======================
Беглый гласный в предлоге: «в втором» → «во втором».

Правило само по себе школьное, но у нас оно возникает не в тексте, а НА СТЫКЕ:
шаблон банка держит предлог («в {corner_no} повороте»), а числительное
приезжает подстановкой из `core/radio/corner_words.py`. Ни одна из сторон не
видит другую, и поэтому ни одна не может исправить стык сама. Результат в эфире
был «в втором повороте» — на каждой трассе календаря, во всех репликах коуча
всех четырёх фаз, с момента появления номеров поворотов.

Почему отдельный модуль, а не строчка в `phrases.render`: тот же стык есть у
строк, идущих в эфир МИМО банка (`core/strategy_ai/sector_comparison.py` —
«во втором секторе»). Две копии правила со временем разошлись бы, и предлог
чинился бы в подсказках коуча, но не в сводке по разрывам.

Область намеренно узкая. Полное правило беглого гласного требует фонетики
(«во Франции», но «в фарватере»), а у нас есть ровно один порождающий случай —
предлог перед словом на «вт»/«вс». Расширять его догадками нельзя: неверное
«во» слышно так же плохо, как неверное «в».
"""
from __future__ import annotations

import re

#: «в» + пробел + слово на «вт»/«вс». Именно эти две связки порождают
#: числительные («втором») и местоимения («всём»); остальное — не наш случай.
#: Регистр сохраняется: вариант банка может начинаться этим предлогом.
_V_BEFORE_CLUSTER = re.compile(r"(?<![А-Яа-яЁё])([Вв])(\s+в[тс])", re.UNICODE)


def fix_prepositions(text: str) -> str:
    """«в втором» → «во втором». Идемпотентна: «во втором» уже не совпадает с
    шаблоном (перед пробелом стоит «о», а не граница слова)."""
    if not text:
        return text
    return _V_BEFORE_CLUSTER.sub(
        lambda m: ("В" if m.group(1) == "В" else "в") + "о" + m.group(2), text)
