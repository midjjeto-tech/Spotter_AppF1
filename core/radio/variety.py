"""
core/radio/variety.py
=====================
Анти-повтор: инженер не произносит одну и ту же формулировку подряд.

Почему это НЕ в `phrases.py`. Банк по своему контракту — чистый реестр плюс
рендер: ни состояния, ни памяти. Здесь памяти не избежать — «что прозвучало
в прошлый раз» нельзя вычислить из ключа ситуации. Разделение простое: банк
отвечает «как коротко сказать», этот модуль — «какую из равноценных
формулировок мы только что уже произносили».

Что именно чинится. `phrases.select_variant` берёт индекс как
`crc32(ключ) % len(пул)`. Это закрепляет вариант за СИТУАЦИЕЙ, и ломать это
нельзя: повторный пакет телеметрии по той же ситуации обязан дать ту же
строку, иначе он перепишет уже произнесённую реплику. Но закрепление работает
per-ключ, а между РАЗНЫМИ ключами crc32 сталкивается — пул из шести вариантов
даёт совпадения постоянно. Замер до этой работы: из двадцати срабатываний
`drs.in_range` три подряд давали одну и ту же строку.

Решение сохраняет оба свойства сразу:

  * решение по ключу запоминается (`_pinned`) — та же ситуация даёт ту же
    строку, сколько бы раз её ни отрендерили;
  * НОВЫЙ ключ, попавший на тот же индекс, что и предыдущая выданная реплика,
    сдвигается на +1 — соседние ситуации звучат по-разному.

Тот же приём, что у `commentator/phrase_pool.py` (там shuffle-bag «не повторять,
пока колода не исчерпана»), но слабее и намеренно: shuffle-bag не совместим с
закреплением за ситуацией, а закрепление здесь важнее полного перебора.

Память сбрасывается на старте заезда — рядом с `reset_phrase_cycles()`
(`core/engine.py`, обработка SSTA): новый заезд начинается с чистого листа.
"""
from __future__ import annotations

import threading

#: Потолок на число запомненных ситуаций. Движок живёт часами, ключи ситуаций
#: уникальны (в них входит id заезда и круг), поэтому без потолка это течёт.
#: 512 с запасом перекрывает заезд: столько РАЗНЫХ ситуаций за гонку не
#: набирается. При переполнении закрепление старых ситуаций теряется, и это
#: безопасно — старая ситуация уже озвучена и повториться не может.
MAX_PINNED = 512

_lock = threading.RLock()
#: (код спеки, ключ ситуации) -> выданный индекс. Держит закрепление.
_pinned: dict[tuple[str, str], int] = {}
#: код спеки -> недавно выданные индексы, свежий последним. Держит анти-повтор.
#: Ключ — только код, без персонажа: у одной спеки общий пул и пул персонажа
#: живут под одним ключом. Персонаж по ходу заезда не меняется (это настройка),
#: поэтому на практике смешения нет; а если игрок переключит его посреди гонки,
#: худшее последствие — одна реплика выберется не тем индексом, что могла бы.
#: Ради этого случая заводить второй ключ дороже, чем он стоит.
_recent: dict[str, list[int]] = {}


def _window(pool_size: int) -> int:
    """Сколько последних формулировок считаем «только что сказанными».

    Половина пула. Памяти в один шаг мало: она убирает соседние повторы, но на
    пуле из шести crc32 всё равно выдавал одну строку три раза за восемь
    реплик — ухо это ловит. Половина пула означает, что строка не может
    вернуться раньше, чем через три другие.

    Больше половины брать нельзя: чем уже остаток, тем сильнее выбор
    определяется историей, а не ключом ситуации, и тем меньше смысла в crc32.
    """
    return pool_size // 2


def index_for(code: str, selector_key: str, base_index: int,
              pool_size: int) -> int:
    """Индекс варианта с учётом того, что уже прозвучало.

    `base_index` — решение банка (crc32). Оно уважается всегда, кроме случая,
    когда новая ситуация попала на строку из недавнего окна: тогда берётся
    ближайшая следующая свободная. Поиск идёт по кругу и ограничен размером
    пула, поэтому завершается всегда; окно меньше пула, поэтому свободная
    строка существует.

    Пул из одного варианта возвращается как есть: повтор там неизбежен, и
    притворяться, что это не так, хуже, чем повториться.
    """
    if pool_size <= 1:
        return 0
    pin = (code, selector_key)
    with _lock:
        pinned = _pinned.get(pin)
        if pinned is not None:
            return pinned

        recent = _recent.setdefault(code, [])
        index = base_index % pool_size
        for step in range(pool_size):
            candidate = (base_index + step) % pool_size
            if candidate not in recent:
                index = candidate
                break

        if len(_pinned) >= MAX_PINNED:
            # Полная очистка, а не вытеснение по одному: LRU здесь стоил бы
            # больше кода и памяти, чем экономит. Терять закрепление старых
            # ситуаций безопасно (см. комментарий к MAX_PINNED).
            _pinned.clear()
        _pinned[pin] = index
        recent.append(index)
        window = _window(pool_size)
        if len(recent) > window:
            del recent[:-window]
        return index


def reset() -> None:
    """Забыть историю. Вызывается на старте заезда."""
    with _lock:
        _pinned.clear()
        _recent.clear()


def pinned_count() -> int:
    """Сколько ситуаций запомнено. Для теста на утечку."""
    with _lock:
        return len(_pinned)
