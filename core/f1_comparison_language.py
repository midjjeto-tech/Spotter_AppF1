"""Формулировки для сравнения времён круга.

ПЕРЕПИСАНО 2026-08-08 вместе со сменой источника эталона. Прежние тексты
оговаривали несопоставимость игры и РЕАЛЬНОГО Гран-при: там отличались физика,
регламент, топливо и состояние трассы, и разница времён не значила почти
ничего. Того сравнения больше нет (Jolpica/OpenF1 удалены, см. NOTICE), а
оставшиеся два сравнения ведутся внутри игры:

- быстрейший круг поля этой же сессии (core/f1_benchmark.py);
- собственный заезд из архива (analytics/comparator.py).

Оговорка нужна и здесь, но другая и короче: физика и регламент одни и те же,
расходятся условия заезда — топливо, резина, погода, настройки. Поэтому «не
показывает, кто быстрее как пилот» ушло: между двумя кругами в одной сессии
разница как раз о темпе. Осталось честное «условия заездов различаются».
"""

from __future__ import annotations


COMPARISON_DISCLAIMER = (
    "Условия заездов различаются: топливо, резина, погода и настройки машины. "
    "Разница времён — ориентир по темпу, а не точное измерение."
)

SHORT_COMPARISON_DISCLAIMER = (
    "Условия заездов различаются — это ориентир по темпу."
)


def describe_time_difference(gap_ms: int | None, *, decimals: int = 1) -> str:
    """Описать записанную разницу, не превращая её в приговор пилоту."""
    if gap_ms is None:
        return "Разница времён недоступна."
    seconds = abs(gap_ms) / 1000.0
    value = f"{seconds:.{decimals}f} с"
    if gap_ms < 0:
        return f"Твоё время на {value} меньше ориентира."
    if gap_ms > 0:
        return f"Твоё время на {value} больше ориентира."
    return "Твоё время совпало с ориентиром."
