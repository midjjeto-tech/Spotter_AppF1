def _pick(pool: list[str], key: str) -> str:
    """Draw from a shuffle bag so a pool is exhausted before it repeats."""
    return pick_phrase(pool, f"commentary:{key}")


def render_rare(pool_key: str) -> str | None:
    """Pick a weighted phrase from a rare pool, or None if key unknown."""
    pool = RARE_POOL.get(pool_key)
    if not pool:
        return None
    phrases, weights = zip(*pool)
    return random.choices(phrases, weights=weights, k=1)[0]


def render_ambient(persona: str = "tv") -> str:
    """Return an ambient observation for persona, avoiding back-to-back repeats."""
    pool = _AMBIENT_POOL.get(persona) or _AMBIENT_POOL["tv"]
    return _pick(pool, f"ambient:{persona}")


